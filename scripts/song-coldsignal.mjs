// "Cold Signal" — F minor, 98 BPM, half-time. Dark pop.
//
// The first song written after `scripts/apollo-probe.mjs` established what the
// synth can actually do. Everything before it used three wavetables, two filter
// types and four effects, which is most of why the catalogue sounds like one
// synth with the filter in different places. Here the character comes from the
// synthesis, and each voice is built around one thing the probe verified:
//
//   Growl   oscillator SYNC, swept by an envelope on every note — a timbral
//           attack rather than a filter one. This is the hook; in dark pop the
//           bass is the melody.
//   Cold    an INHARMONIC spectral warp on a bell table. Partials pulled off
//           the harmonic series is the difference between a bell and a synth
//           playing a bell patch.
//   Fog     a FORMANT filter whose vowel is morphed by a LORENZ chaos LFO —
//           chaos rather than a sine, because a pad that breathes on a
//           repeating cycle announces the cycle.
//   Wire    Apollo's own ARP through a SAMPLE-AND-HOLD filter. The texture is
//           generated by the synth from a held chord rather than written out.
//
// THE HARMONY is i–♭VI–iv–♭II in F minor: Fm9, D♭maj7, B♭m11, G♭maj7♯11. The
// last chord is the Neapolitan, and it is the whole reason this sounds dark
// rather than merely minor — a major chord a semitone above the tonic, which
// wants to fall back onto it and never quite does. The ♯11 keeps its fourth off
// the third. Voiced ROOTLESS: the bass owns the root.
//
// THE GROOVE is half-time — rim on beat 3 only, kick on 1 and the push before
// 3 — which is what gives dark pop its slowness at a tempo that is not actually
// slow. The pump on the pad and keys is an editable gain curve in the FX lane
// rather than a compressor nobody can see.
//
// No lead line, by standing rule. The arp is the chord moving, not a phrase.

import { writeFileSync, mkdirSync } from 'fs'
import { join, dirname } from 'path'
import { homedir } from 'os'
import { execFileSync } from 'child_process'
import { fileURLToPath } from 'url'
import { uid, N, assemble, dipInto, lift, bar } from './song-kit.mjs'
import { groove, play, voice, parseChord, intoSlot, checkSlots, stagger, densityArc, thin, pump, rng } from './lib/craft.mjs'
import { kick, rimSnap, gritHats, subBass, growlBass, coldKeys, fogPad, wireArp } from './apollo-voices.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = join(homedir(), 'Desktop', '100lights-ai-renders')
const argv = process.argv.slice(2)
const flagOf = (n, d) => { const a = argv.find(x => x.startsWith(`--${n}=`)); return a ? a.split('=')[1] : d }

const BPM = 98, BPB = 4
const g = groove({ bpm: BPM, feel: 'straight', swing: 0, seed: 1174 })
const rand = rng(1174)

// ── Harmony ─────────────────────────────────────────────────────────────────
const LOOP = ['Fm9', 'Dbmaj7', 'Bbm11', 'Gbmaj7#11']
const ROOTS = { Fm9: 41, Dbmaj7: 37, Bbm11: 46, 'Gbmaj7#11': 42 }

const VOICED = []
let prev = null
for (const sym of LOOP) {
  // Three sounding notes: these play under a pad and an arp, and a fourth voice
  // costs polyphony without being heard.
  const v = voice(sym, { style: 'rootless', centre: 62, spread: 10, near: prev }).slice(0, 3)
  VOICED.push(v)
  prev = v
}

const SLOT = { sub: 'sub', growl: 'bass', fog: 'lowChord', cold: 'chord', wire: 'upper' }
const collisions = checkSlots(SLOT)
if (collisions.length) throw new Error('register collision: ' + collisions.join('; '))

// ── Parts ───────────────────────────────────────────────────────────────────
const KICK = 24, RIM = 48, HAT = 60

/** Half-time: beat 1, and a push into 3. Nothing on the backbeat but the rim. */
const kickBar = ({ busy = false } = {}) => {
  const hits = busy ? [0, 2.75, 3.5] : [0, 2.75]
  return hits.map(b => ({ pitch: KICK, beat: b, durationBeats: 0.4, velocity: b === 0 ? 106 : 92 }))
}
const rimBar = ({ fill = false } = {}) => {
  const out = [{ pitch: RIM, beat: 2, durationBeats: 0.25, velocity: 98 }]
  if (fill) for (const b of [3.5, 3.75]) out.push({ pitch: RIM, beat: b, durationBeats: 0.18, velocity: 62 + (b - 3.5) * 80 })
  return out
}
const hatBar = ({ sixteenths = false } = {}) => {
  const out = []
  const step = sixteenths ? 0.25 : 0.5
  for (let b = 0; b < BPB; b += step) {
    if (rand() < (sixteenths ? 0.3 : 0.12)) continue        // holes: a machine plays them all
    const open = Math.abs(b % 2 - 1.5) < 0.01
    out.push({ pitch: HAT, beat: b, durationBeats: open ? 0.3 : 0.06, velocity: open ? 62 : 48 })
  }
  return out
}

const subBar = (i) => {
  // An octave below the bass, not in unison with it. Sharing the same five
  // semitones with the Growl made two parts fight for one register and cost the
  // low end its definition.
  const root = intoSlot(ROOTS[LOOP[i % 4]] - 12, 'sub')
  return [{ pitch: root, beat: 0, durationBeats: BPB - 0.2, velocity: 88 }]
}

/**
 * The hook. Sixteenth syncopation with an octave pop, and it rests across beat
 * two so the half-time kick has room — a busy bar everywhere would fill the gap
 * that makes this feel slow.
 */
const growlBar = (i, { lean = false } = {}) => {
  const c = LOOP[i % 4]
  const root = intoSlot(ROOTS[c], 'bass')
  // Take the seventh from the CHORD, not from a fixed interval. Hardcoding a
  // minor seventh put an E under G♭maj7 and a B under D♭maj7 — a semitone under
  // each chord's major seventh, which is not a colour, it is a wrong note. The
  // note checker found it; the ear would have found it faster.
  const tones = parseChord(c).tones
  const fifth = root + (tones.find(t => t === 7) ?? 7)
  const seventh = root + (tones.find(t => t === 10 || t === 11) ?? 10)
  const octave = root + 12
  const figure = lean
    ? [[root, 0, 0.9, 104], [root, 2.5, 0.45, 88]]
    : [[root, 0, 0.42, 106], [root, 0.75, 0.22, 82], [octave, 1.25, 0.3, 94],
       [root, 2.5, 0.35, 100], [seventh, 3.0, 0.28, 86], [fifth, 3.5, 0.4, 90]]
  return figure.map(([p, b, d, v]) => ({ pitch: intoSlot(p, 'bass'), beat: b, durationBeats: d, velocity: v }))
}

/** Struck on the "and" of 1 and on 4 — off the kick, off the rim. */
const coldBar = (i, { sparse = false } = {}) => {
  const v = VOICED[i % 4]
  const hits = sparse ? [[0.5, 2.6, 64]] : [[0.5, 1.5, 74], [3.0, 0.9, 60]]
  const out = []
  for (const [b, d, vel] of hits) {
    v.forEach((p, k) => out.push({
      pitch: intoSlot(p, 'chord'), beat: b + k * 0.006, durationBeats: d, velocity: vel - k * 4,
    }))
  }
  return out
}

/** One held chord per bar, low and wide — the room the song sits in. */
const fogBar = (i) => VOICED[i % 4].map(p => ({
  pitch: intoSlot(p, 'lowChord'), beat: 0, durationBeats: BPB - 0.15, velocity: 40,
}))

/** A held chord; Apollo's arp turns it into sixteenths. */
const wireBar = (i) => VOICED[i % 4].map(p => ({
  pitch: intoSlot(p, 'upper'), beat: 0, durationBeats: BPB - 0.1, velocity: 56,
}))

// ── Form ────────────────────────────────────────────────────────────────────
const FORM = [
  { name: 'Signal', bars: 6,  energy: 0.12, want: ['fog', 'cold'] },
  { name: 'Pulse',  bars: 6,  energy: 0.34, want: ['fog', 'cold', 'sub', 'growl', 'hats'] },
  { name: 'Body A', bars: 10, energy: 0.82, want: ['fog', 'cold', 'sub', 'growl', 'kick', 'hats'] },
  { name: 'Vacuum', bars: 6,  energy: 0.08, want: ['fog', 'cold'] },
  { name: 'Body B', bars: 10, energy: 1.00, want: ['fog', 'cold', 'sub', 'growl', 'kick', 'hats', 'wire'] },
  { name: 'Static', bars: 8,  energy: 0.62, want: ['fog', 'sub', 'growl', 'kick', 'hats', 'wire'] },
  { name: 'Out',    bars: 8,  energy: 0.22, want: ['fog', 'cold'] },
]
const { sections: staggered, unresolved } = stagger(FORM, { maxChurn: 2 })
if (unresolved.length) console.warn('arrangement:\n  ' + unresolved.join('\n  '))
const DENSITY = densityArc(FORM.map(s => s.energy))

export function build() {
  const tracks = [
    { key: 'kick',  id: uid(), name: 'Kick',  presetId: null, volume: 0.85, color: '#f0abfc', instrument: { type: 'apollo', params: kick() } },
    { key: 'rim',   id: uid(), name: 'Rim',   presetId: null, volume: 0.62, color: '#f472b6', instrument: { type: 'apollo', params: rimSnap() } },
    { key: 'hats',  id: uid(), name: 'Hats',  presetId: null, volume: 0.40, pan: 0.20, color: '#fda4af', instrument: { type: 'apollo', params: gritHats() } },
    { key: 'sub',   id: uid(), name: 'Sub',   presetId: null, volume: 0.72, color: '#c084fc', instrument: { type: 'apollo', params: subBass() } },
    { key: 'growl', id: uid(), name: 'Growl', presetId: null, volume: 0.62, color: '#a78bfa', instrument: { type: 'apollo', params: growlBass() } },
    { key: 'cold',  id: uid(), name: 'Cold',  presetId: null, volume: 0.34, pan: -0.16, color: '#7dd3fc', instrument: { type: 'apollo', params: coldKeys() } },
    { key: 'fog',   id: uid(), name: 'Fog',   presetId: null, volume: 0.014, pan: 0.10, color: '#94a3b8', instrument: { type: 'apollo', params: fogPad() } },
    { key: 'wire',  id: uid(), name: 'Wire',  presetId: null, volume: 0.34, pan: 0.26, color: '#6ee7b7', instrument: { type: 'apollo', params: wireArp() } },
  ]

  const sections = staggered.map((sec, si) => {
    const on = new Set(sec.layers)
    const density = DENSITY[si]
    const parts = {}
    const push = (k, notes) => { (parts[k] ??= []).push(...notes) }

    for (let i = 0; i < sec.bars; i++) {
      const at = i * BPB
      const last = i === sec.bars - 1
      const busy = density > 0.7
      const shift = ns => ns.map(n => ({ ...n, beat: n.beat + at }))

      if (on.has('fog')) push('fog', shift(fogBar(i)))
      if (on.has('cold')) push('cold', shift(coldBar(i, { sparse: density < 0.4 })))
      if (on.has('sub')) push('sub', shift(subBar(i)))
      if (on.has('growl')) push('growl', shift(growlBar(i, { lean: density < 0.5 })))
      if (on.has('kick')) push('kick', shift(kickBar({ busy })))
      if (on.has('kick')) push('rim', shift(rimBar({ fill: last && busy })))
      if (on.has('hats')) push('hats', shift(hatBar({ sixteenths: busy })))
      if (on.has('wire')) push('wire', shift(wireBar(i)))
    }

    if (density < 0.5) {
      for (const k of ['cold', 'hats']) if (parts[k]) parts[k] = thin(parts[k], 0.4 + density, { bpb: BPB })
    }

    // Quiet sections are played softer, not just emptier. Without this the
    // arrangement changes while the level does not, and the drop is inaudible.
    const dyn = 0.42 + 0.58 * density

    const ROLE = { kick: 'kick', rim: 'snare', hats: 'hats', sub: 'sub', growl: 'bass', cold: 'keys', fog: 'pad', wire: 'arp' }
    const played = {}
    for (const [k, ns] of Object.entries(parts)) {
      played[k] = play(ns, ROLE[k] ?? 'default', g, { bpb: BPB })
        .map(n => N(n.pitch, n.beat, n.durationBeats, Math.max(1, Math.round(n.velocity * dyn))))
    }
    return { name: sec.name, bars: sec.bars, parts: played }
  })

  // ── Dynamics in the FX lane ───────────────────────────────────────────────
  const at = {}
  let acc = 0
  for (const s of staggered) { at[s.name] = acc; acc += s.bars * BPB }
  const W = bars => bars * BPB

  const bars = [
    // Duck on every kick. Written as a curve because a compressor keyed off the
    // kick would be invisible and uneditable, and this is the gesture that makes
    // the record breathe.
    pump('fog', at['Body A'], W(10), { depth: 0.62, recover: 0.6 }),
    pump('fog', at['Body B'], W(10), { depth: 0.58, recover: 0.6 }),
    pump('fog', at['Static'], W(8), { depth: 0.66, recover: 0.6 }),
    pump('cold', at['Body B'], W(10), { depth: 0.74, recover: 0.5 }),

    // Close the filter and duck before each arrival so the arrival lands.
    dipInto('cold', at['Body A'], 3),
    dipInto('growl', at['Body B'], 2),
    dipInto('fog', at['Body B'], 3, 1),

    // Push across the peaks.
    lift('growl', at['Body A'], W(10), { drive: 0.05, gain: 1.1 }),
    lift('growl', at['Body B'], W(10), { drive: 0.06, gain: 1.12 }),

    // The drop-out sits behind a closed filter and a wide reverb, then opens on
    // the way out of it.
    bar('fog', at['Vacuum'], W(6), { filterHz: 760, reverbWet: 0.5 },
        [[0, 1], [W(4), 1], [W(6), 0.1]], 1),
    bar('cold', at['Vacuum'], W(6), { filterHz: 1100 }, [[0, 1], [W(5), 0.9], [W(6), 0.2]], 1),

    // Static is the last build: the arp brightens and the hats open up.
    bar('wire', at['Static'], W(8), { filterHz: 1400, gain: 0.8 }, [[0, 1], [W(6), 0.2], [W(8), 0]], 0),

    // Outro: the instruments leave, the reverb tails keep ringing.
    bar('cold', at['Out'] + W(4), W(4), { gain: 0.15, filterHz: 640 }, [[0, 0], [W(4), 1]], 2),
    bar('fog', at['Out'] + W(4), W(4), { gain: 0.25, filterHz: 800 }, [[0, 0], [W(4), 1]], 3),
  ]

  return assemble({
    name: 'Cold Signal', bpm: BPM, bpb: BPB, key: 'F', scale: 'minor',
    swing: 0, tracks, sections, bars, masterVolume: 0.46,
  })
}

// ── Run ─────────────────────────────────────────────────────────────────────
const built = build()
mkdirSync(OUT_DIR, { recursive: true })
const label = flagOf('label', 'Cold Signal')
const outFile = join(flagOf('out', OUT_DIR), `${label}.cfproj`)
writeFileSync(outFile, JSON.stringify(built.project))

const clips = built.project.dawProject.arrangementClips
console.log(`${label} — ${BPM} BPM, F minor, ${built.seconds.toFixed(0)}s, ${clips.length} clips, ` +
  `${clips.reduce((a, c) => a + c.notes.length, 0)} notes, ${built.project.dawProject.clipEffects.length} fx bars`)
for (const s of staggered) console.log(`  ${s.name.padEnd(8)} ${String(s.bars).padStart(2)} bars  ${s.layers.join(' ')}`)
console.log(`→ ${outFile}`)

if (argv.includes('--listen')) {
  execFileSync('node', ['--experimental-strip-types', join(ROOT, 'scripts/listen.mjs'), outFile, '--target=general'],
    { cwd: ROOT, stdio: 'inherit' })
}
