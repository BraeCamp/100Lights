#!/usr/bin/env node
// Measure each background clip's brightness from its bundled poster (perceptual luminance)
// and bucket into dark / mid / bright. Deterministic, non-AI — just averages pixels. Writes
// lib/bg-brightness.ts (BRIGHTNESS_MAP: id -> 'bright'|'mid'|'dark') consumed by clipBrightness().
//
//   node scripts/tag-bg-brightness.mjs --dry     # print the luminance distribution only
//   node scripts/tag-bg-brightness.mjs           # write lib/bg-brightness.ts
//
// Thresholds are on 0–255 perceptual luma (Rec.709). Tune with --dark / --bright.
import sharp from 'sharp'
import { readdir, writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIRS = ['public/bg/nature', 'public/bg/generative']
const arg = (k, d) => { const i = process.argv.indexOf(k); return i >= 0 ? Number(process.argv[i + 1]) : d }
const DARK_MAX = arg('--dark', 78)     // luma < DARK_MAX  -> dark
const BRIGHT_MIN = arg('--bright', 150) // luma >= BRIGHT_MIN -> bright  (else mid)
const DRY = process.argv.includes('--dry')

async function lumaOf(file) {
  // Downscale for speed; .stats() gives per-channel means over the whole image.
  const s = await sharp(file).resize(64, 64, { fit: 'inside' }).stats()
  const [r, g, b] = s.channels
  return 0.2126 * r.mean + 0.7152 * g.mean + 0.0722 * b.mean
}

const rows = []
for (const dir of DIRS) {
  let files = []
  try { files = (await readdir(join(ROOT, dir))).filter(f => f.endsWith('.jpg')) } catch { continue }
  for (const f of files) {
    const id = f.replace(/\.jpg$/, '')
    try { rows.push({ id, luma: await lumaOf(join(ROOT, dir, f)) }) } catch { /* skip unreadable */ }
  }
}
rows.sort((a, b) => a.luma - b.luma)

const bucket = l => (l < DARK_MAX ? 'dark' : l >= BRIGHT_MIN ? 'bright' : 'mid')
const counts = { dark: 0, mid: 0, bright: 0 }
for (const r of rows) counts[bucket(r.luma)]++

if (DRY) {
  for (const r of rows) console.log(`${bucket(r.luma).padEnd(6)} ${r.luma.toFixed(0).padStart(4)}  ${r.id}`)
  console.log(`\n${rows.length} posters · dark<${DARK_MAX} bright>=${BRIGHT_MIN}  →  dark ${counts.dark} · mid ${counts.mid} · bright ${counts.bright}`)
  process.exit(0)
}

const map = Object.fromEntries(rows.map(r => [r.id, bucket(r.luma)]))
const body = `// AUTO-GENERATED by scripts/tag-bg-brightness.mjs — do not edit by hand.
// Perceptual-luminance brightness of each background poster (0–255 Rec.709 luma), bucketed
// dark<${DARK_MAX} / bright>=${BRIGHT_MIN}. Regenerate after adding clips: npm run bg:brightness
export type Brightness = 'bright' | 'mid' | 'dark'
export const BRIGHTNESS_MAP: Record<string, Brightness> = ${JSON.stringify(map, null, 2)}
`
await writeFile(join(ROOT, 'lib/bg-brightness.ts'), body)
console.log(`Wrote lib/bg-brightness.ts · ${rows.length} clips · dark ${counts.dark} · mid ${counts.mid} · bright ${counts.bright}`)
