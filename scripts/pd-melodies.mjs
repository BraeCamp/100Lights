// Childish or seasonal tunes — kept in the library (reachable via --song=<slug>) but EXCLUDED from
// random content, which should sound universal, not like a nursery rhyme or a Christmas carol.
const NOT_APPLICABLE = new Set([
  'twinkle', 'mary', 'london_bridge', 'row_boat', 'frere_jacques', 'hot_cross_buns',   // kids
  'jingle_bells', 'silent_night', 'deck_the_halls', 'we_wish',                          // holiday
])
export const RANDOM_KEYS = Object.keys(MELODIES).filter(k => !NOT_APPLICABLE.has(k))

// Pick a melody: by explicit slug (any tune), or RANDOM from the applicable set (no kids/holiday).
export function pickMelody(slug, rng = Math.random) {
  if (slug && MELODIES[slug]) return { slug, ...MELODIES[slug] }
  const k = RANDOM_KEYS[Math.floor(rng() * RANDOM_KEYS.length)]
  return { slug: k, ...MELODIES[k] }
}
export const MELODY_SLUGS = Object.keys(MELODIES)
